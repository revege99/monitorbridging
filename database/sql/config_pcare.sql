-- Run on each clinic database that does not yet contain config_pcare.
CREATE TABLE IF NOT EXISTS config_pcare (
    id TINYINT UNSIGNED NOT NULL,
    SECRETKEYAPIPCARE TEXT NOT NULL,
    CONSIDAPIPCARE TEXT NOT NULL,
    USERKEYAPIPCARE TEXT NOT NULL,
    PASSPCARE TEXT NOT NULL,
    USERPCARE TEXT NOT NULL,
    PRIMARY KEY (id)
) ENGINE=INNODB DEFAULT CHARSET=utf8mb4;
